const month = "march"

switch (month) {
    case "jan":
        console.log("january");
        break;
    case 2:
        console.log("february");
        break;
    case "march":
        console.log("march");
        break;
    case 4:
        console.log("april");
        break;
    default:
        console.log("default case match");
        break;
}

// break nhi hoga toh match hue case k neeche ke saare cases match ho jayenge except default
// lekin default k upar wale mein agar break nhi hoga toh default bhi match hoga

